#!/usr/bin/env python3
"""Derive complete runtime WAVs and C header from the source-of-truth catalog.

Originals remain untouched under assets/original and are source-only. No local
inventory paths, accounts, or hosted-storage identifiers are published.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import tempfile
import wave

ROOT = Path(__file__).resolve().parents[1]


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def load_catalog(root=ROOT):
    catalog = json.loads((root / 'assets/catalog.json').read_text(encoding='utf-8'))
    clips = catalog['clips']
    if catalog['schema_version'] != 1 or not clips:
        raise ValueError('Unsupported or empty clip catalog')
    if catalog['runtime_format'] != {'codec': 'pcm_s16le', 'sample_rate': 48000, 'channels': 2, 'sample_width_bytes': 2}:
        raise ValueError('Unsupported runtime PCM format')
    ids = set()
    filenames = set()
    for clip in clips:
        clip_id = clip['id']
        filename = clip['source_filename']
        if not re.fullmatch(r'[a-z][a-z0-9_]*', clip_id) or clip_id in ids:
            raise ValueError('Unsafe or duplicate clip ID')
        if filename != Path(filename).name or '/' in filename or '\\' in filename or filename in filenames:
            raise ValueError('Unsafe or duplicate source filename')
        if clip['runtime_file'] != f'{clip_id}.wav':
            raise ValueError('Runtime filename must match clip ID')
        if not clip['label'] or not re.fullmatch(r'[0-9a-f]{64}', clip['source_sha256']):
            raise ValueError('Missing label or invalid source hash')
        if not isinstance(clip['expected_frames'], int) or clip['expected_frames'] <= 0:
            raise ValueError('Invalid expected PCM frame count')
        ids.add(clip_id)
        filenames.add(filename)
    return catalog


def write_header(catalog, root=ROOT):
    """Generate the only C-side catalog; invalid indices return empty strings."""
    clips = catalog['clips']
    def c_string(value):
        return json.dumps(value, ensure_ascii=False)
    ids = ',\n'.join('        ' + c_string(clip['id']) for clip in clips)
    labels = ',\n'.join('        ' + c_string(clip['label']) for clip in clips)
    header = f'''/* Generated by scripts/build_assets.py from assets/catalog.json. */
#ifndef GAMEVOICEBOX_CLIP_CATALOG_H
#define GAMEVOICEBOX_CLIP_CATALOG_H
#define CLIP_COUNT {len(clips)}

/* UTF-8 IDs/labels, with checked bounds for all public lookups. */
static inline const char *clip_catalog_id(int index) {{
    static const char *const ids[CLIP_COUNT] = {{
{ids}
    }};
    return index >= 0 && index < CLIP_COUNT ? ids[index] : "";
}}

static inline const char *clip_catalog_label(int index) {{
    static const char *const labels[CLIP_COUNT] = {{
{labels}
    }};
    return index >= 0 && index < CLIP_COUNT ? labels[index] : "";
}}
#endif
'''
    destination = root / 'src/app/clip_catalog.h'
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(header, encoding='utf-8')


def build(root=ROOT, source_dir=None):
    catalog = load_catalog(root)
    assets = root / 'assets'
    originals = assets / 'original'
    source_dir = Path(source_dir) if source_dir is not None else originals
    # Validate every source before modifying any derived runtime files.
    for clip in catalog['clips']:
        source = source_dir / clip['source_filename']
        if not source.is_file() or sha256(source) != clip['source_sha256']:
            raise ValueError('Original asset hash mismatch or missing: ' + clip['id'])
    originals.mkdir(exist_ok=True)
    result = []
    for clip in catalog['clips']:
        source = source_dir / clip['source_filename']
        original = originals / clip['source_filename']
        if source.resolve() != original.resolve():
            if original.exists() and sha256(original) != clip['source_sha256']:
                raise ValueError('Refusing to overwrite changed original: ' + clip['id'])
            if not original.exists():
                shutil.copyfile(source, original)
        destination = assets / clip['runtime_file']
        with tempfile.NamedTemporaryFile(dir=assets, suffix='.wav', delete=False) as temporary:
            temporary_path = Path(temporary.name)
        try:
            subprocess.run(['ffmpeg', '-hide_banner', '-loglevel', 'error', '-nostdin', '-y', '-i', str(original), '-map', '0:a:0', '-ar', '48000', '-ac', '2', '-c:a', 'pcm_s16le', '-fflags', '+bitexact', '-flags:a', '+bitexact', str(temporary_path)], check=True)
            with wave.open(str(temporary_path), 'rb') as wav:
                expected = (48000, 2, 2, clip['expected_frames'], 'NONE')
                actual = (wav.getframerate(), wav.getnchannels(), wav.getsampwidth(), wav.getnframes(), wav.getcomptype())
                if actual != expected:
                    raise ValueError('Decoded PCM format/frame count differs: ' + clip['id'])
                pcm = wav.readframes(wav.getnframes())
            os.replace(temporary_path, destination)
        finally:
            temporary_path.unlink(missing_ok=True)
        frames = clip['expected_frames']
        result.append({'clip': clip['id'], 'label': clip['label'], 'source': clip['source_filename'], 'source_sha256': clip['source_sha256'], 'source_format': clip['source_format'], 'source_audio_codec': clip['source_audio_codec'], 'contains_video': clip['contains_video'], 'extension_mismatch': clip['extension_mismatch'], 'runtime_file': clip['runtime_file'], 'wav_sha256': sha256(destination), 'pcm_sha256': hashlib.sha256(pcm).hexdigest(), 'codec': 'pcm_s16le', 'sample_rate': 48000, 'channels': 2, 'sample_width_bytes': 2, 'frames': frames, 'data_bytes': frames * 4, 'wav_bytes': destination.stat().st_size, 'duration_seconds': round(frames / 48000, 9)})
    (assets / 'integrity.json').write_text(json.dumps(result, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    write_header(catalog, root)
    print('Verified complete runtime WAVs:', len(result))
    print('PCM frames:', [row['frames'] for row in result])
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source-dir', type=Path, help='Import untouched original files once; defaults to assets/original')
    parser.add_argument('--header-only', action='store_true', help='Regenerate C catalog without decoding audio')
    args = parser.parse_args()
    if args.header_only:
        write_header(load_catalog())
    else:
        build(source_dir=args.source_dir)


if __name__ == '__main__':
    main()
